/** The page kind this gate reads; picks the adapter list it binds to. */
const POST_DETAIL_SURFACE = "post-detail" as const;

// ----------------------------------------------------------------------------
// Diagnostic-only selectors ({@link capturePostLoadFailure}).
//
// These no longer feed the readiness predicate.  The predicate is now
// generated from the post-detail adapter registry so it polls the *selected*
// adapter's own anchor; these constants stay because a timeout still wants a
// "which-of-N-is-missing" picture across both dialects' markers, and that
// picture is deliberately wider than any single adapter's binding.
//
// What "wider" means is now exact, and it is what bounds this block (#853).
// The registry's OWN anchors are no longer restated here: the capture reports
// each registered adapter's `ready`, `scopes` and `counts` under that
// adapter's own name, from source generated by
// `buildPostDetailAnchorProbeSource`.  Every constant that survives below is
// one NO adapter anchors on, which is the whole reason a hand-maintained list
// still earns its place — a second copy of a registry anchor would drift, and
// drift silently, reporting a renamed dialect under its old name at the one
// moment the report is being read.  Add a marker here only when it is
// genuinely outside every adapter's binding; anything an adapter owns belongs
// in the registry and arrives through the generator.
// ----------------------------------------------------------------------------

